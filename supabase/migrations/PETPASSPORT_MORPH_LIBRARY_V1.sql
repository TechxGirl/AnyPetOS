-- =====================================================
-- 🟢 PetPassport Morph Library v1 SQL
--
-- Adds a shared morph / breed / variety option table.
-- Community-submitted morphs become selectable for everyone.
-- =====================================================

create table if not exists public.morph_options (
  id bigint generated by default as identity primary key,
  species_key text not null,
  species_name text not null,
  category text,
  animal_group text,
  morph_key text not null,
  morph_name text not null,
  source text not null default 'community',
  status text not null default 'active' check (status in ('active', 'hidden', 'pending')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint morph_options_species_morph_unique unique (species_key, morph_key)
);

alter table public.morph_options enable row level security;

grant select on table public.morph_options to anon, authenticated;
grant insert on table public.morph_options to authenticated;

drop policy if exists "Anyone can read active morph options" on public.morph_options;
drop policy if exists "Authenticated users can add morph options" on public.morph_options;

create policy "Anyone can read active morph options"
on public.morph_options
for select
using (status = 'active');

create policy "Authenticated users can add morph options"
on public.morph_options
for insert
to authenticated
with check (
  auth.uid() = created_by
  and source = 'community'
  and status = 'active'
  and length(trim(species_name)) between 2 and 120
  and length(trim(morph_name)) between 2 and 120
);

create index if not exists morph_options_species_idx
on public.morph_options (species_key, status, morph_name);

