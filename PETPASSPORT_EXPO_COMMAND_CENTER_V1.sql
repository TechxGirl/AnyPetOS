create or replace function public.is_expo_owner(p_event_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.expo_events e
    where e.id = p_event_id
      and e.owner_id = auth.uid()
  );
$$;

create or replace function public.is_expo_vendor(p_event_id bigint, p_require_approved boolean default true)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.expo_event_vendors v
    where v.event_id = p_event_id
      and v.user_id = auth.uid()
      and (not p_require_approved or v.status = 'approved')
  );
$$;

create or replace function public.can_manage_expo_listing(p_listing_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.expo_event_animals a
    join public.expo_events e on e.id = a.event_id
    where a.id = p_listing_id
      and (a.owner_id = auth.uid() or e.owner_id = auth.uid())
  );
$$;


-- Prevent exhibitors from approving themselves or moving a vendor membership
-- to another user/event. Organizers still control approval status.
create or replace function public.guard_expo_vendor_security()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.event_id is distinct from old.event_id or new.user_id is distinct from old.user_id then
    raise exception 'Expo vendor identity and event cannot be changed.';
  end if;

  if new.status is distinct from old.status or new.approved_at is distinct from old.approved_at then
    if public.is_expo_owner(old.event_id) then
      return new;
    end if;

    if new.status = 'pending' and old.status in ('pending', 'rejected', 'withdrawn') then
      new.approved_at := null;
    else
      raise exception 'Only the event organizer can change exhibitor approval status.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists expo_vendor_security_guard on public.expo_event_vendors;
create trigger expo_vendor_security_guard
before update on public.expo_event_vendors
for each row execute function public.guard_expo_vendor_security();

-- Keep listing ownership, PetPassport ownership, event, and vendor membership aligned.
create or replace function public.guard_expo_listing_relationships()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.pets p
    where p.id = new.pet_id and p.user_id = new.owner_id
  ) then
    raise exception 'The listed animal must belong to the listing owner.';
  end if;

  if not exists (
    select 1
    from public.expo_event_vendors v
    where v.id = new.vendor_id
      and v.event_id = new.event_id
      and v.user_id = new.owner_id
  ) then
    raise exception 'The listing vendor, event, and owner do not match.';
  end if;

  return new;
end;
$$;

drop trigger if exists expo_listing_relationship_guard on public.expo_event_animals;
create trigger expo_listing_relationship_guard
before insert or update on public.expo_event_animals
for each row execute function public.guard_expo_listing_relationships();

-- Keep holds connected to the correct event, listing, vendor, and lead.
create or replace function public.guard_expo_hold_relationships()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.expo_event_animals a
    where a.id = new.listing_id
      and a.event_id = new.event_id
      and (new.vendor_id is null or a.vendor_id = new.vendor_id)
  ) then
    raise exception 'The hold does not match the selected expo listing.';
  end if;

  if new.lead_id is not null and not exists (
    select 1
    from public.expo_leads l
    where l.id = new.lead_id
      and l.event_id = new.event_id
      and (l.listing_id is null or l.listing_id = new.listing_id)
      and (new.vendor_id is null or l.vendor_id is null or l.vendor_id = new.vendor_id)
  ) then
    raise exception 'The hold lead does not match the selected expo listing.';
  end if;

  return new;
end;
$$;

drop trigger if exists expo_hold_relationship_guard on public.expo_holds;
create trigger expo_hold_relationship_guard
before insert or update on public.expo_holds
for each row execute function public.guard_expo_hold_relationships();

