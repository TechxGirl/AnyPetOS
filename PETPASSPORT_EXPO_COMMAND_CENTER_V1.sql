  r record;
begin
  for r in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in (
        'expo_events', 'expo_event_vendors', 'expo_event_animals', 'expo_leads',
        'expo_holds', 'expo_event_follows', 'expo_listing_favorites', 'expo_scans',
