create or replace function public.record_expo_scan(
  p_slug text,
  p_listing_token text default null,
  p_scan_type text default 'event',
  p_referrer text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_id bigint;
  v_listing_id bigint;
begin
  select e.id into v_event_id
  from public.expo_events e
  where e.slug = p_slug
    and e.is_public = true
    and e.status in ('Published', 'Live', 'Completed')
    and (e.public_expires_at is null or now() < e.public_expires_at)
  limit 1;

  if v_event_id is null then return false; end if;

  if p_listing_token is not null then
    select a.id into v_listing_id
    from public.expo_event_animals a
    where a.event_id = v_event_id
      and a.listing_token = p_listing_token
      and a.show_in_catalog = true
      and a.status <> 'Not attending'
    limit 1;
  end if;

  insert into public.expo_scans(event_id, listing_id, scan_type, referrer, user_agent)
  values (v_event_id, v_listing_id, coalesce(nullif(p_scan_type, ''), 'event'), left(p_referrer, 1000), left(coalesce(nullif(current_setting('request.headers', true), '')::jsonb->>'user-agent', ''), 1000));

  return true;
exception when others then
  return false;
end;
$$;

create or replace function public.submit_expo_interest(
  p_slug text,
  p_listing_token text,
  p_name text,
  p_email text default '',
  p_phone text default '',
  p_preferred_contact text default 'Email',
  p_interest_level text default 'Interested',
  p_timeframe text default '',
  p_hold_requested boolean default false,
  p_message text default '',
  p_consent_to_follow_up boolean default false
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event public.expo_events%rowtype;
  v_listing public.expo_event_animals%rowtype;
  v_lead_id bigint;
begin
  select * into v_event
  from public.expo_events e
  where e.slug = p_slug
    and e.is_public = true
    and e.status in ('Published', 'Live')
    and (e.public_expires_at is null or now() < e.public_expires_at)
    and e.allow_interest = true
  limit 1;

  if v_event.id is null then
    raise exception 'This expo is not accepting interest forms.';
  end if;

  select * into v_listing
  from public.expo_event_animals a
  where a.event_id = v_event.id
    and a.listing_token = p_listing_token
    and a.show_in_catalog = true
    and a.status not in ('Sold', 'Adopted', 'Not attending')
  limit 1;

  if v_listing.id is null then
    raise exception 'This animal is no longer available for public interest.';
  end if;

  if length(trim(coalesce(p_name, ''))) < 2 then
    raise exception 'Please provide your name.';
  end if;

  if not p_consent_to_follow_up then
    raise exception 'Follow-up consent is required before sending contact details.';
  end if;

  insert into public.expo_leads (
    event_id, listing_id, vendor_id, name, email, phone, preferred_contact,
    interest_level, timeframe, hold_requested, message, consent_to_follow_up,
    status, source
  ) values (
    v_event.id,
    v_listing.id,
    v_listing.vendor_id,
    left(trim(p_name), 160),
    left(lower(trim(coalesce(p_email, ''))), 320),
    left(trim(coalesce(p_phone, '')), 80),
    left(trim(coalesce(p_preferred_contact, 'Email')), 80),
    left(trim(coalesce(p_interest_level, 'Interested')), 100),
    left(trim(coalesce(p_timeframe, '')), 120),
    case when v_event.allow_hold_requests then coalesce(p_hold_requested, false) else false end,
    left(trim(coalesce(p_message, '')), 4000),
    true,
    case when coalesce(p_hold_requested, false) and v_event.allow_hold_requests then 'Hold requested' else 'New' end,
    'public-expo'
  ) returning id into v_lead_id;

  return v_lead_id;
end;
$$;

create or replace function public.set_expo_kiosk_pin(p_event_id bigint, p_pin text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not public.is_expo_owner(p_event_id) then
    raise exception 'Only the event organizer can set the kiosk PIN.';
  end if;

  if length(trim(coalesce(p_pin, ''))) < 4 then
    raise exception 'Use a kiosk PIN with at least four characters.';
  end if;

  update public.expo_events
  set kiosk_pin_hash = crypt(trim(p_pin), gen_salt('bf')),
      kiosk_pin_required = true,
      updated_at = now()
  where id = p_event_id;

  return true;
end;
$$;

create or replace function public.verify_expo_kiosk_pin(p_slug text, p_pin text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions
as $$
  select coalesce((
    select
      case
        when e.kiosk_pin_required = false then true
        when e.kiosk_pin_hash is null then false
        else e.kiosk_pin_hash = crypt(trim(coalesce(p_pin, '')), e.kiosk_pin_hash)
      end
    from public.expo_events e
    where e.slug = p_slug and e.is_public = true
    limit 1
  ), false);
$$;


create or replace function public.release_expired_expo_holds(p_event_id bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer := 0;
  v_hold record;
begin
  if not (public.is_expo_owner(p_event_id) or public.is_expo_vendor(p_event_id, true)) then
    return 0;
  end if;

  for v_hold in
    select h.id, h.listing_id, h.lead_id
    from public.expo_holds h
    where h.event_id = p_event_id
      and h.status = 'active'
      and h.expires_at is not null
      and h.expires_at <= now()
  loop
    update public.expo_holds
    set status = 'expired', released_at = now(), updated_at = now()
    where id = v_hold.id;

    update public.expo_event_animals
    set status = 'Available', updated_at = now()
    where id = v_hold.listing_id and status = 'On hold';

    if v_hold.lead_id is not null then
      update public.expo_leads
      set status = 'Contacted', updated_at = now()
      where id = v_hold.lead_id and status = 'Hold requested';
    end if;

    v_count := v_count + 1;
  end loop;

  return v_count;
end;
$$;

create or replace function public.get_expo_event_analytics(p_event_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not (public.is_expo_owner(p_event_id) or public.is_expo_vendor(p_event_id, true)) then
    raise exception 'You do not have access to this expo analytics report.';
  end if;

  return jsonb_build_object(
    'views', (select count(*) from public.expo_scans s where s.event_id = p_event_id),
    'followers', (select count(*) from public.expo_event_follows f where f.event_id = p_event_id),
    'favorites', (select count(*) from public.expo_listing_favorites f where f.event_id = p_event_id),
    'leads', (select count(*) from public.expo_leads l where l.event_id = p_event_id),
    'holds', (select count(*) from public.expo_holds h where h.event_id = p_event_id),
    'completed', (
      select count(*) from public.expo_event_animals a
      where a.event_id = p_event_id and a.status in ('Sold', 'Adopted')
    ),
    'listing_views', coalesce((
      select jsonb_agg(jsonb_build_object(
        'listing_id', a.id,
        'display_name', a.display_name,
        'listing_code', a.listing_code,
        'count', coalesce(v.view_count, 0)
      ) order by coalesce(v.view_count, 0) desc, a.display_name)
      from public.expo_event_animals a
      left join (
        select listing_id, count(*) as view_count
        from public.expo_scans
        where event_id = p_event_id and listing_id is not null
        group by listing_id
      ) v on v.listing_id = a.id
      where a.event_id = p_event_id
    ), '[]'::jsonb),
    'listing_favorites', coalesce((
      select jsonb_agg(jsonb_build_object(
        'listing_id', a.id,
        'display_name', a.display_name,
        'listing_code', a.listing_code,
        'count', coalesce(f.favorite_count, 0)
      ) order by coalesce(f.favorite_count, 0) desc, a.display_name)
      from public.expo_event_animals a
      left join (
        select listing_id, count(*) as favorite_count
        from public.expo_listing_favorites
        where event_id = p_event_id
        group by listing_id
      ) f on f.listing_id = a.id
      where a.event_id = p_event_id
    ), '[]'::jsonb)
  );
end;
$$;

