-- =====================================================
-- Shared updated_at trigger
-- =====================================================

create or replace function public.petpassport_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

DO $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'expo_events',
    'expo_event_vendors',
    'expo_event_animals',
    'expo_leads',
    'expo_holds',
    'expo_updates'
  ]
  loop
    execute format('drop trigger if exists %I on public.%I', table_name || '_updated_at', table_name);
    execute format(
      'create trigger %I before update on public.%I for each row execute function public.petpassport_set_updated_at()',
      table_name || '_updated_at',
      table_name
    );
  end loop;
end;
$$;

